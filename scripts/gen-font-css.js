// Generates src/app/fonts.css from public/fonts/manifest.json:
// :root --font-* variables + one @font-face per vendored woff2.
// Re-run after refreshing fonts via scripts/fetch-fonts.js.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "public", "fonts", "manifest.json"), "utf8"));

const SERIF = ["DM Serif Display", "Playfair Display", "Cormorant Garamond", "EB Garamond", "Cinzel", "Pinyon Script", "Italianno", "Dancing Script", "Alex Brush", "Lora", "Baskervville", "Cormorant", "Bitter", "Allura", "Parisienne", "Waterfall", "Ysabeau Infant"];
const CURSIVE = ["Caveat", "Knewave"];
const VAR = {
  Inter: "--font-inter",
  "Playfair Display": "--font-playfair",
  "Cormorant Garamond": "--font-cormorant",
  "Dancing Script": "--font-dancing",
  "Plus Jakarta Sans": "--font-plusjakarta",
  "EB Garamond": "--font-ebgaramond",
  Italianno: "--font-italianno",
  "Press Start 2P": "--font-pressstart",
  "Alex Brush": "--font-alexbrush",
  Montserrat: "--font-montserrat",
  Cinzel: "--font-cinzel",
  "Pinyon Script": "--font-pinyon",
  "Public Sans": "--font-publicsans",
  Baskervville: "--font-baskervville",
  Jura: "--font-jura",
  Lora: "--font-lora",
  Poppins: "--font-poppins",
  Cormorant: "--font-cormorant-ref",
  Bitter: "--font-bitter",
  Allura: "--font-allura",
  Parisienne: "--font-parisienne",
  Caveat: "--font-caveat",
  Knewave: "--font-knewave",
  "DM Sans": "--font-dmsans",
  "DM Serif Display": "--font-dmserif",
  Anton: "--font-anton",
  Archivo: "--font-archivo",
  "DM Mono": "--font-dmmono",
  Jost: "--font-jost",
  Waterfall: "--font-waterfall",
  "Ysabeau Infant": "--font-ysabeau",
};

let css = "/* Vendored Google Fonts (latin woff2) — generated by scripts/gen-font-css.js. DO NOT EDIT. */\n:root {\n";
for (const [family, v] of Object.entries(VAR)) {
  const fallback = CURSIVE.includes(family) ? "cursive" : SERIF.includes(family) ? "serif" : family === "Press Start 2P" ? "monospace" : "sans-serif";
  css += `  ${v}: '${family}', ${fallback};\n`;
}
css += "}\n";

for (const [file, m] of Object.entries(manifest)) {
  css += `@font-face {\n  font-family: '${m.family}';\n  font-style: ${m.style};\n  font-weight: ${m.weight};\n  font-display: swap;\n  src: url('/fonts/${file}') format('woff2');\n}\n`;
}

fs.writeFileSync(path.join(ROOT, "src", "app", "fonts.css"), css);
console.log("wrote src/app/fonts.css");
